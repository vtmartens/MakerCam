/**
 * Project persistence.
 *
 * Projects are ordinary SVG files with a <metadata> section describing the
 * CAM operations. Saved files open in any SVG viewer, and files written by the
 * original Flash MakerCam/PartKam can be loaded as well.
 */

import {
  Bounds,
  Path,
  Vec,
  flattenPath,
} from './geom';
import {
  DEFAULT_PARAMS,
  Direction,
  OpDefinition,
  OperationParams,
  OperationType,
  Unit,
} from './cam';
import { parseSvg, pathToSvgD, ImportOptions } from './svg';

export interface ProjectData {
  paths: Path[];
  operations: OpDefinition[];
  unit: Unit;
  widthMm: number;
  heightMm: number;
  warnings: string[];
}

function escapeXml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

function round(n: number, decimals = 4): number {
  const f = Math.pow(10, decimals);
  return Math.round(n * f) / f;
}

function allBounds(paths: Path[]): Bounds {
  let b: Bounds | null = null;
  for (const p of paths) {
    for (const q of flattenPath(p, 0.05)) {
      if (!b) b = { minX: q.x, minY: q.y, maxX: q.x, maxY: q.y };
      else {
        b.minX = Math.min(b.minX, q.x);
        b.minY = Math.min(b.minY, q.y);
        b.maxX = Math.max(b.maxX, q.x);
        b.maxY = Math.max(b.maxY, q.y);
      }
    }
  }
  return b ?? { minX: 0, minY: 0, maxX: 0, maxY: 0 };
}

const PARAM_KEYS = [
  'toolDiameter',
  'targetDepth',
  'safetyHeight',
  'stockSurface',
  'stepdown',
  'feedrate',
  'plungerate',
  'outside',
  'direction',
  'stepover',
  'roughingClearance',
  'center',
  'spacing',
  'holeCount',
  'tabSpacing',
  'tabWidth',
  'tabHeight',
] as const;

export function serializeProject(
  paths: Path[],
  operations: OpDefinition[],
  unit: Unit = 'mm',
): string {
  const b = allBounds(paths);
  const w = Math.max(b.maxX - b.minX, 0.001);
  const h = Math.max(b.maxY - b.minY, 0.001);
  const map = (p: Vec): Vec => ({ x: p.x - b.minX, y: b.maxY - p.y });

  const lines: string[] = [];
  lines.push(`<?xml version="1.0" encoding="UTF-8"?>`);
  lines.push(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${round(w)}mm" height="${round(h)}mm" viewBox="0 0 ${round(w)} ${round(h)}">`,
  );
  lines.push('  <metadata>');
  lines.push(
    `    <partkam-project version="2" unit="mm" width="${round(w)}" height="${round(h)}">`,
  );
  for (const op of operations) {
    const attrs = [
      `id="${escapeXml(op.id ?? '')}"`,
      `type="${op.type}"`,
      `name="${escapeXml(op.name)}"`,
    ];
    for (const key of PARAM_KEYS) {
      const v = (op.params as any)[key];
      if (typeof v === 'boolean') attrs.push(`${key}="${v}"`);
      else if (typeof v === 'number' && Number.isFinite(v)) attrs.push(`${key}="${round(v, 6)}"`);
    }
    lines.push(`      <partkam-operation ${attrs.join(' ')}>`);
    for (const pathId of op.pathIds) {
      lines.push(`        <partkam-path ref="${escapeXml(pathId)}"/>`);
    }
    lines.push('      </partkam-operation>');
  }
  lines.push('    </partkam-project>');
  lines.push('  </metadata>');
  lines.push('  <!-- Generated by MakerCam Modern (a port of PartKam by Jack Clark) -->');
  for (const p of paths) {
    const id = p.id || 'path';
    const d = pathToSvgD(p, map);
    if (!d) continue;
    lines.push(
      `  <path id="${escapeXml(id)}" d="${escapeXml(d)}" fill="none" stroke="#000000" stroke-width="0.2"/>`,
    );
  }
  lines.push('</svg>');
  return lines.join('\n');
}

function readNumber(el: Element, name: string, fallback: number): number {
  const v = el.getAttribute(name);
  if (v == null || v === '') return fallback;
  const n = Number(v);
  return Number.isFinite(n) ? n : fallback;
}

function readBoolean(el: Element, name: string, fallback: boolean): boolean {
  const v = el.getAttribute(name);
  if (v == null) return fallback;
  return v === 'true';
}

function readDirection(el: Element, fallback: Direction): Direction {
  const v = el.getAttribute('direction');
  return v === '2' ? 2 : v === '1' ? 1 : fallback;
}

function elementLocalName(el: Element): string {
  return (el.localName || el.nodeName || '').toLowerCase();
}

function pathMapBySource(paths: Path[]): Map<string, Path[]> {
  const map = new Map<string, Path[]>();
  for (const p of paths) {
    const keys = [p.id, p.sourceId, p.name].filter(Boolean) as string[];
    for (const k of keys) {
      const list = map.get(k) ?? [];
      list.push(p);
      map.set(k, list);
    }
  }
  return map;
}

/** Parses a project file. Returns null if the SVG has no MakerCam metadata. */
export function parseProject(text: string, options: ImportOptions = {}): ProjectData | null {
  const imported = parseSvg(text, options);
  const parser = new DOMParser();
  const doc = parser.parseFromString(text, 'image/svg+xml');
  if (doc.querySelector('parsererror')) return null;

  const metadataEls = Array.from(doc.getElementsByTagName('*')).filter(
    (el) => elementLocalName(el) === 'metadata',
  );
  if (metadataEls.length === 0) return null;

  const projectEl = Array.from(doc.getElementsByTagName('*')).find(
    (el) => elementLocalName(el) === 'partkam-project',
  );
  const pathMap = pathMapBySource(imported.paths);
  const warnings = [...imported.warnings];

  if (projectEl) {
    const operations: OpDefinition[] = [];
    const opEls = Array.from(projectEl.getElementsByTagName('*')).filter(
      (el) => elementLocalName(el) === 'partkam-operation',
    );
    for (const el of opEls) {
      const type = (el.getAttribute('type') || 'profile') as OperationType;
      const params: OperationParams = { ...DEFAULT_PARAMS('mm') };
      for (const key of PARAM_KEYS) {
        const attr = el.getAttribute(key);
        if (attr == null) continue;
        if (key === 'outside' || key === 'center') {
          (params as any)[key] = attr === 'true';
        } else if (key === 'direction') {
          params.direction = attr === '2' ? 2 : 1;
        } else {
          const n = Number(attr);
          if (Number.isFinite(n)) (params as any)[key] = n;
        }
      }
      const refs = Array.from(el.getElementsByTagName('*'))
        .filter((c) => elementLocalName(c) === 'partkam-path')
        .map((c) => c.getAttribute('ref') || '')
        .filter(Boolean);
      const pathIds: string[] = [];
      for (const ref of refs) {
        const found = pathMap.get(ref);
        if (found && found.length > 0) {
          for (const p of found) if (p.id && !pathIds.includes(p.id)) pathIds.push(p.id);
        } else {
          warnings.push(`Saved operation "${el.getAttribute('name') || ''}" references a missing path.`);
        }
      }
      operations.push({
        id: el.getAttribute('id') || `op${operations.length + 1}`,
        type,
        name: el.getAttribute('name') || `${type} ${operations.length + 1}`,
        params,
        pathIds,
      });
    }
    return {
      paths: imported.paths,
      operations,
      unit: 'mm',
      widthMm: imported.widthMm,
      heightMm: imported.heightMm,
      warnings,
    };
  }

  // Original MakerCam/PartKam metadata: <metadata><cutobject ...>
  const cutEls = Array.from(doc.getElementsByTagName('*')).filter(
    (el) => elementLocalName(el) === 'cutobject',
  );
  if (cutEls.length === 0) return null;

  const operations: OpDefinition[] = [];
  for (const el of cutEls) {
    const type = (el.getAttribute('type') || 'profile') as OperationType;
    const sourceUnit = (el.getAttribute('unit') || 'imperial').toLowerCase();
    const metric = sourceUnit === 'metric';
    const params: OperationParams = { ...DEFAULT_PARAMS('mm') };
    // Original internal units: inch or cm for lengths; machining values are
    // inch (imperial) or mm (metric).
    const machScale = metric ? 1 : 25.4; // machining params -> mm
    const toolScale = metric ? 10 : 25.4; // cm or inch -> mm
    params.safetyHeight = readNumber(el, 'safetyheight', 0) * machScale;
    params.stockSurface = readNumber(el, 'stocksurface', 0) * machScale;
    params.targetDepth = readNumber(el, 'targetdepth', 0) * machScale;
    params.stepdown = Math.abs(readNumber(el, 'stepdown', 1)) * machScale || 1;
    params.feedrate = Math.abs(readNumber(el, 'feedrate', 1)) * machScale || 1;
    params.plungerate = Math.abs(readNumber(el, 'plungerate', 1)) * machScale || 1;
    params.toolDiameter = Math.abs(readNumber(el, 'tooldiameter', 1)) * toolScale;
    params.roughingClearance = Math.abs(readNumber(el, 'roughingclearance', 0)) * toolScale;
    params.stepover = Math.abs(readNumber(el, 'stepover', 0.4));
    if (params.stepover > 1) params.stepover /= 100;
    params.outside = readBoolean(el, 'outside', true);
    params.direction = readDirection(el, 1);
    params.center = readBoolean(el, 'center', true);
    params.spacing = Math.abs(readNumber(el, 'spacing', 0)) * toolScale;
    params.tabSpacing = 0;
    params.tabWidth = 0;
    params.tabHeight = 0;

    const refs = Array.from(el.getElementsByTagName('*'))
      .filter((c) => elementLocalName(c) === 'path')
      .map((c) => (c.textContent || '').trim())
      .filter(Boolean);
    const pathIds: string[] = [];
    for (const ref of refs) {
      const found = pathMap.get(ref);
      if (found) {
        for (const p of found) if (p.id && !pathIds.includes(p.id)) pathIds.push(p.id);
      }
    }
    operations.push({
      id: `op${operations.length + 1}`,
      type,
      name: el.getAttribute('name') || `${type} ${operations.length + 1}`,
      params,
      pathIds,
    });
  }

  return {
    paths: imported.paths,
    operations,
    unit: 'mm',
    widthMm: imported.widthMm,
    heightMm: imported.heightMm,
    warnings,
  };
}

/** Triggers a browser download. */
export function downloadText(filename: string, text: string, mime = 'text/plain'): void {
  const blob = new Blob([text], { type: `${mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
